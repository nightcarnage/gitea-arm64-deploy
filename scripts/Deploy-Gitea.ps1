<#
.SYNOPSIS
    Deploy a self-hosted Gitea with one command, and create an admin account.

.DESCRIPTION
    Idempotent: run it as many times as you like. It will not duplicate users or
    destroy data.

      1. verifies Docker is actually responding,
      2. writes .env if it does not exist,
      3. pulls the image and starts the container,
      4. waits until the HTTP API answers (not just until the container is "up"),
      5. creates an admin user if that user does not already exist,
      6. issues an API token and saves it to .gitea-token,
      7. prints the URLs and credentials.

    The container is configured so that Gitea's first-run install wizard never
    appears (INSTALL_LOCK), because a wizard that must be clicked through by hand
    makes unattended deployment impossible.

.EXAMPLE
    .\scripts\Deploy-Gitea.ps1

.EXAMPLE
    .\scripts\Deploy-Gitea.ps1 -HttpPort 3300 -SshPort 3222 -AdminUser me -AdminPassword 'secret123'

.NOTES
    .gitea-token contains a credential. It is in .gitignore; do not commit it.
#>
[CmdletBinding()]
param(
    [int]$HttpPort = 3000,
    [int]$SshPort  = 3022,
    [string]$AdminUser     = 'gitadmin',
    [string]$AdminPassword = 'changeme123',
    [string]$AdminEmail    = 'admin@localhost.local',
    [string]$Tz            = 'UTC',
    [string]$TokenName     = 'cli',
    # How long to wait for the HTTP API to answer, in seconds.
    [int]$TimeoutSec = 240,
    [switch]$Force
)

# Deliberately 'Continue', not 'Stop'. Native tools (docker, git, netsh) write ordinary
# progress and warnings to stderr, and under 'Stop' a redirected `2>&1` turns that into a
# terminating error - docker compose pull ("Image gitea/gitea:1 Pulling") aborts the run.
# Every native call is therefore checked explicitly via $LASTEXITCODE below, and anything
# that can genuinely throw is wrapped in try/catch.
$ErrorActionPreference = 'Continue'

function Step($t) { Write-Host "`n== $t" -ForegroundColor Cyan }
function Good($t) { Write-Host "   OK   $t" -ForegroundColor Green }
function Warn($t) { Write-Host "   WARN $t" -ForegroundColor Yellow }
function Bad($t)  { Write-Host "   FAIL $t" -ForegroundColor Red }

$root      = Split-Path -Parent $PSScriptRoot
$compose   = Join-Path $root 'compose.yaml'
$envFile   = Join-Path $root '.env'
$tokenFile = Join-Path $root '.gitea-token'
$baseUrl   = "http://localhost:$HttpPort"

if (-not (Test-Path $compose)) { Bad "No compose.yaml next to the scripts folder ($compose)"; exit 1 }

# ------------------------------------------------------------------ docker available?
Step 'Checking Docker'
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Bad 'docker is not on PATH. Install Docker Desktop.'; exit 1
}
& docker info *> $null
if ($LASTEXITCODE -ne 0) {
    Bad 'The Docker engine is not responding.'
    Bad 'Start Docker Desktop and wait until it says "Engine running".'
    exit 1
}
$srvArch = (& docker version --format '{{.Server.Arch}}' 2>&1 | Out-String).Trim()
Good "engine responding (linux/$srvArch)"

# --------------------------------------------------------------------------- .env file
Step 'Configuration'
if (-not (Test-Path $envFile) -or $Force) {
    $envContent = @"
# Generated by scripts\Deploy-Gitea.ps1 - safe to edit, just re-run the script.
HTTP_PORT=$HttpPort
SSH_PORT=$SshPort
TZ=$Tz
GITEA_ADMIN_USER=$AdminUser
GITEA_ADMIN_PASSWORD=$AdminPassword
GITEA_ADMIN_EMAIL=$AdminEmail
"@
    Set-Content -Path $envFile -Value $envContent -Encoding ASCII
    Good "wrote .env (http $HttpPort, ssh $SshPort)"
} else {
    # Honour whatever .env already says, so re-runs do not silently move ports.
    $existing = Get-Content $envFile
    foreach ($line in $existing) {
        if ($line -match '^\s*HTTP_PORT\s*=\s*(\d+)') { $HttpPort = [int]$Matches[1] }
        if ($line -match '^\s*SSH_PORT\s*=\s*(\d+)')  { $SshPort  = [int]$Matches[1] }
        if ($line -match '^\s*GITEA_ADMIN_USER\s*=\s*(.+)$')     { $AdminUser     = $Matches[1].Trim() }
        if ($line -match '^\s*GITEA_ADMIN_PASSWORD\s*=\s*(.+)$') { $AdminPassword = $Matches[1].Trim() }
        if ($line -match '^\s*GITEA_ADMIN_EMAIL\s*=\s*(.+)$')    { $AdminEmail    = $Matches[1].Trim() }
    }
    $baseUrl = "http://localhost:$HttpPort"
    Good "using existing .env (http $HttpPort, ssh $SshPort, admin $AdminUser)"
}

# Warn early about a port Windows will refuse to bind.
$reservedOut = & netsh interface ipv4 show excludedportrange protocol=tcp 2>&1
foreach ($line in $reservedOut) {
    if ($line -match '^\s*(\d+)\s+(\d+)(\s+\*)?\s*$') {
        $s = [int]$Matches[1]; $e = [int]$Matches[2]
        foreach ($p in @($HttpPort, $SshPort)) {
            if ($p -ge $s -and $p -le $e) {
                Bad "Port $p is inside a Windows-reserved range ($s-$e)."
                Bad 'Windows will refuse to bind it. Pick another port, e.g. -SshPort 3222'
                exit 1
            }
        }
    }
}

# --------------------------------------------------------------------- pull and start
Step 'Starting Gitea'
Push-Location $root
try {
    & docker compose pull --quiet 2>$null | Out-Null
    # No redirection: letting docker print straight to the console avoids turning its
    # stderr progress into pipeline ErrorRecords.
    & docker compose up -d
    if ($LASTEXITCODE -ne 0) { Bad 'docker compose up failed. See the output above.'; exit 1 }
} finally { Pop-Location }
Good 'container started'

# ------------------------------------------------------------------------ wait healthy
Step 'Waiting for the API'
$deadline = (Get-Date).AddSeconds($TimeoutSec)
$ready = $false
while ((Get-Date) -lt $deadline) {
    try {
        $v = Invoke-RestMethod -Uri "$baseUrl/api/v1/version" -TimeoutSec 5 -ErrorAction Stop
        if ($v.version) { Good "Gitea $($v.version) answering at $baseUrl"; $ready = $true; break }
    } catch { }
    Start-Sleep -Seconds 3
}
if (-not $ready) {
    Bad "No answer from $baseUrl after $TimeoutSec seconds."
    Push-Location $root; & docker compose logs --tail 30; Pop-Location
    exit 1
}

# -------------------------------------------------------------------------- admin user
Step 'Admin account'
$listOut = (& docker compose -f $compose exec -T -u git gitea gitea admin user list 2>&1 | Out-String)
if ($listOut -match "(?m)^\d+\s+$([regex]::Escape($AdminUser))\s") {
    Good "user '$AdminUser' already exists - left alone"
} else {
    $createOut = (& docker compose -f $compose exec -T -u git gitea gitea admin user create `
        --username $AdminUser --password $AdminPassword --email $AdminEmail `
        --admin --must-change-password=false 2>&1 | Out-String)
    if ($LASTEXITCODE -eq 0) { Good "created admin '$AdminUser'" }
    else {
        Bad "could not create '$AdminUser':"
        Write-Host $createOut -ForegroundColor DarkGray
        if ($createOut -match '(?i)password') {
            Bad "Gitea refused the password (minimum length). Use at least 6 characters."
        }
        exit 1
    }
}

# ---------------------------------------------------------------------------- api token
Step 'API token'
if (Test-Path $tokenFile) {
    Good ".gitea-token already present (delete it to issue a new one)"
} else {
    $tokOut = (& docker compose -f $compose exec -T -u git gitea gitea admin user generate-access-token `
        --username $AdminUser --token-name $TokenName --scopes all --raw 2>&1 | Out-String)
    $tok = ($tokOut -split "`n" | Where-Object { $_.Trim() } | Select-Object -Last 1).Trim()
    if ($tok -and $tok -notmatch '\s' -and $tok.Length -ge 20) {
        Set-Content -Path $tokenFile -Value $tok -Encoding ASCII
        Good "issued token and saved to .gitea-token"
    } else {
        Warn 'could not read a token back.'
        Warn 'A token named "' + $TokenName + '" may already exist - delete it in the web UI, then re-run.'
    }
}

# ------------------------------------------------------------------------- final summary
Write-Host ""
Write-Host "================================================" -ForegroundColor Green
Write-Host " Gitea is running" -ForegroundColor Green
Write-Host "================================================" -ForegroundColor Green
Write-Host "  Web UI   : $baseUrl"
Write-Host "  Login    : $AdminUser / $AdminPassword"
Write-Host "  HTTP git : $baseUrl/<owner>/<repo>.git"
Write-Host "  SSH git  : ssh://git@localhost:$SshPort/<owner>/<repo>.git"
Write-Host "  Data     : docker volume gitea-data (kept by 'docker compose down')"
Write-Host "  Token    : .gitea-token (gitignored)"
Write-Host ""
Write-Host "  Stop:    docker compose down" -ForegroundColor DarkGray
Write-Host "  Destroy: docker compose down -v   (deletes ALL repositories)" -ForegroundColor DarkGray
Write-Host ""
Write-Host "Next: create a project wired for an AI agent" -ForegroundColor Cyan
Write-Host "  .\scripts\New-Project.ps1 -Name MyProject -Kind unity" -ForegroundColor Cyan
Write-Host ""
